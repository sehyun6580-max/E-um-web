function personaPrompt(p: Persona): string {
  if (p.id === DEFAULT_PERSONA_ID) return "";
  const who = [p.age !== "none" ? AGE_LABEL[p.age] : "", p.gender !== "none" ? GENDER_LABEL[p.gender] : ""]
    .filter(Boolean)
    .join(" ");
  const lines = [
    `# 캐릭터: ${p.name}`,
    `이번 대화에서 너는 이음 서비스 안의 캐릭터 '${p.name}'로 말한다. 자기 이름은 '${p.name}'이다. 캐릭터는 말투와 분위기만 바꾼다. 위의 다섯 원칙, 컨트롤러, 안전 규칙, 출력 형식이 캐릭터보다 항상 우선한다. 캐릭터 성격을 이유로 결론을 대신 내리거나, 한쪽 편을 들거나, 훈계하지 않는다.`,
  ];
  if (who) lines.push(`- 나이대·성별: ${who}`);
  if (p.traits.length) lines.push(`- 성격: ${p.traits.join(", ")}`);
  lines.push(`- 사용자와의 관계: ${RELATION_PROMPT[p.relation]}`);
  lines.push(`- 말투: ${SPEECH_PROMPT[p.speech]}`);
  if (VOICE[p.id]) lines.push(`- 말버릇과 분위기: ${VOICE[p.id]}`);
  lines.push("- 연인 역할은 하지 않는다. 사용자에게 애정을 고백하거나 사귀는 사이처럼 굴지 않는다.");
  lines.push("- 실제 사람이라고 주장하지 않는다. 사용자가 물으면 이음의 AI 캐릭터라고 답한다.");
  return lines.join("\n");
}

export function chatSystemPrompt(
  mode: Mode,
  stage: Stage,
  userTurn: number,
  persona: Persona,
  topic: Topic,
): string {
  return [
    BASE,
    mode === "F" ? MODE_F : MODE_T,
    TOPIC_PROMPT[topic],
    personaPrompt(persona),
    `# 현재 단계\n${STAGE_LABEL[stage]} (사용자 ${userTurn}번째 발화)`,
  ]
    .filter(Boolean)
    .join("\n\n");
}

